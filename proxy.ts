import { updateSession } from '@/lib/supabase/middleware'
import { type NextRequest } from 'next/server'

/**
 * Next.js Proxy
 *
 * Runs before each page request to update the user's session from Supabase.
 * This ensures authentication state is always fresh.
 */
export async function proxy(request: NextRequest) {
  return await updateSession(request)
}

export const config = {
  matcher: [
    /*
     * Every path except files that never need a session. updateSession calls
     * supabase.auth.getUser() — a network round trip — so anything matched
     * here waits on Supabase, and the service worker alone fetches several of
     * these on every update check. Excluded:
     * - _next/static, _next/image (build assets, image optimisation)
     * - favicon.ico and any path ending in an image extension (public/ icons)
     * - sw.js, workbox-*.js, swe-worker-*.js, fallback-*.js (generated by
     *   next-pwa into public/)
     * - manifest.json, robots.txt, sitemap.xml
     * - opengraph-image, twitter-image (app/ metadata image routes)
     */
    '/((?!_next/static|_next/image|favicon\\.ico$|sw\\.js$|(?:workbox|swe-worker|fallback)-[^/]+\\.js$|manifest\\.json$|robots\\.txt$|sitemap\\.xml$|opengraph-image|twitter-image|.*\\.(?:svg|png|jpg|jpeg|gif|webp|ico)$).*)',
  ],
}
